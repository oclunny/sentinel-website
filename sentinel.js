/* =====================================================================
   I18N ENGINE
   ===================================================================== */
let currentLang = localStorage.getItem('sentinel-lang') || 'en';

function applyTranslations(lang) {
  const t = translations[lang];
  if (!t) return;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key] !== undefined) el.innerHTML = t[key];
  });
  document.documentElement.lang = lang;
  const langCurrent = document.getElementById('langCurrent');
  if (langCurrent) langCurrent.textContent = lang.toUpperCase();
  document.querySelectorAll('.lang-option, .lang-option-mobile').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });
  currentLang = lang;
  localStorage.setItem('sentinel-lang', lang);
}

/* =====================================================================
   LANG SWITCHER
   ===================================================================== */
const langBtn = document.getElementById('langBtn');
const langDropdown = document.getElementById('langDropdown');

langBtn && langBtn.addEventListener('click', (e) => {
  e.stopPropagation();
  langDropdown.classList.toggle('open');
});

document.addEventListener('click', () => {
  langDropdown && langDropdown.classList.remove('open');
});

document.querySelectorAll('.lang-option').forEach(btn => {
  btn.addEventListener('click', () => {
    applyTranslations(btn.dataset.lang);
    langDropdown.classList.remove('open');
  });
});

document.querySelectorAll('.lang-option-mobile').forEach(btn => {
  btn.addEventListener('click', () => applyTranslations(btn.dataset.lang));
});

/* =====================================================================
   THEME
   ===================================================================== */
const body = document.body;
const themeBtn = document.getElementById('themeBtn');
const iconSun = document.getElementById('iconSun');
const iconMoon = document.getElementById('iconMoon');

function applyTheme(isLight) {
  body.classList.toggle('light', isLight);
  if (iconSun) iconSun.style.display = isLight ? 'block' : 'none';
  if (iconMoon) iconMoon.style.display = isLight ? 'none' : 'block';
}

themeBtn && themeBtn.addEventListener('click', () => {
  const isLight = !body.classList.contains('light');
  applyTheme(isLight);
  localStorage.setItem('sentinel-theme', isLight ? 'light' : 'dark');
});

/* =====================================================================
   NAV SCROLL
   ===================================================================== */
const nav = document.getElementById('nav');
window.addEventListener('scroll', () => {
  nav && nav.classList.toggle('scrolled', window.scrollY > 20);
}, { passive: true });

/* =====================================================================
   BURGER
   ===================================================================== */
const burger = document.getElementById('burger');
const mobileMenu = document.getElementById('mobileMenu');
burger && burger.addEventListener('click', () => {
  burger.classList.toggle('open');
  mobileMenu && mobileMenu.classList.toggle('open');
});

/* =====================================================================
   SCROLL REVEAL
   ===================================================================== */
document.querySelectorAll('.showcase-item, .feat-card, .cta-card, .about-text, .about-features').forEach(el => {
  el.classList.add('reveal');
});

const observer = new IntersectionObserver((entries) => {
  entries.forEach(entry => {
    if (entry.isIntersecting) entry.target.classList.add('visible');
  });
}, { threshold: 0.08, rootMargin: '0px 0px -50px 0px' });

document.querySelectorAll('.reveal').forEach(el => observer.observe(el));

/* =====================================================================
   INIT — run on DOM ready
   ===================================================================== */
window.addEventListener('DOMContentLoaded', () => {
  const savedTheme = localStorage.getItem('sentinel-theme');
  applyTheme(savedTheme === 'light');
  applyTranslations(currentLang);
});
